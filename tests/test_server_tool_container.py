class _FakeStream:
    def __init__(self, message):
        self._message = message

    def __enter__(self):
        return self

    def __exit__(self, *args):
        return False

    def get_final_message(self):
        return self._message


class _FakeMessagesAPI:
    def __init__(self, route):
        self._route = route
        self.calls: list[dict] = []

    def stream(self, **kwargs):
        self.calls.append(kwargs)
        result = self._route(kwargs)
        if isinstance(result, Exception):
            raise result
        return _FakeStream(result)


class _FakeClient:
    def __init__(self, route):
        self.messages = _FakeMessagesAPI(route)

    @property
    def calls(self) -> list[dict]:
        return self.messages.calls


def _sequential(responses: list):
    """Route successive calls through ``responses`` in order."""
    remaining = list(responses)

    def route(_kwargs):
        assert remaining, "fake client ran out of scripted responses"
        return remaining.pop(0)

    return route


def _with_container(message, container_id: str | None):
    """Return ``message`` carrying (or not carrying) a container object."""
    return dataclasses.replace(
        message,
        container=FakeContainer(id=container_id) if container_id else None,
    )


def _finding() -> Finding:
    return Finding(
        severity="HIGH",
        fileName="21 10 00 - Water-Based Fire Protection.docx",
        section="2.1",
        issue="Cited sprinkler standard edition may not match local adoption.",
        actionType="REPORT_ONLY",
        existingText=None,
        replacementText=None,
        codeReference="NFPA 13",
        confidence=0.7,
    )


