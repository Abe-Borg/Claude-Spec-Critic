def _run_research(responses: list):
    client = _FakeClient(_sequential(responses))
    profile = run_requirements_research(
        _enabled_module(), _profile(), client=client
    )
    return profile, client


class TestResearchContinuationCarriesContainer:
    def test_resume_after_a_pause_names_the_container(self):
        """The regression that lost two production research dimensions."""
        paused = _with_container(
            pause_turn_response(searched_urls=[SEARCHED_URL]), CONTAINER_ID
        )
        done = _with_container(
            research_tool_use_response(
                payload=_research_payload(), searched_urls=[SEARCHED_URL]
            ),
            CONTAINER_ID,
        )
        _profile_out, client = _run_research([paused, done])

        assert len(client.calls) == 2, "expected one initial call and one resume"
        assert "container" not in client.calls[0], "initial call provisions the container"
        assert client.calls[1]["container"] == CONTAINER_ID

    def test_container_survives_a_turn_that_reports_none(self):
        """A turn that ran no code execution reports no container — but the
        conversation still belongs to the one an earlier turn created, so the
        id must be carried forward rather than dropped."""
        first = _with_container(
            pause_turn_response(searched_urls=[SEARCHED_URL]), CONTAINER_ID
        )
        second = _with_container(pause_turn_response(), None)
        done = _with_container(
            research_tool_use_response(
                payload=_research_payload(), searched_urls=[SEARCHED_URL]
            ),
            None,
        )
        _profile_out, client = _run_research([first, second, done])

        assert len(client.calls) == 3
        assert client.calls[1]["container"] == CONTAINER_ID
        assert client.calls[2]["container"] == CONTAINER_ID

    def test_a_newer_container_id_supersedes_the_earlier_one(self):
        first = _with_container(
            pause_turn_response(searched_urls=[SEARCHED_URL]), CONTAINER_ID
        )
        second = _with_container(pause_turn_response(), SECOND_CONTAINER_ID)
        done = _with_container(
            research_tool_use_response(
                payload=_research_payload(), searched_urls=[SEARCHED_URL]
            ),
            None,
        )
        _profile_out, client = _run_research([first, second, done])

        assert client.calls[1]["container"] == CONTAINER_ID
        assert client.calls[2]["container"] == SECOND_CONTAINER_ID


