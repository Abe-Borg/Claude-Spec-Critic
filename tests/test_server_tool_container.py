class TestNoContainerKeepsBodyIdentical:
    def test_initial_verification_request_has_no_container_key(self):
        decision = select_routing(
            _finding(), escalated=False, local_skip=False, cycle=DEFAULT_CYCLE
        )
        request = build_verification_request(
            decision, prompt="p", system_prompt="s"
        )
        assert "container" not in request.params

    def test_continuation_without_an_id_has_no_container_key(self):
        request = V._build_continuation_request(
            "original prompt",
            [{"type": "text", "text": "prior turn"}],
            cycle=DEFAULT_CYCLE,
            model="claude-sonnet-5",
            severity="HIGH",
            finding=_finding(),
            container_id=None,
        )
        assert "container" not in request.params

    def test_research_conversation_without_containers_sends_no_key(self):
        paused = _with_container(
            pause_turn_response(searched_urls=[SEARCHED_URL]), None
        )
        done = _with_container(
            research_tool_use_response(
                payload=_research_payload(), searched_urls=[SEARCHED_URL]
            ),
            None,
        )
        _profile_out, client = _run_research([paused, done])
        assert all("container" not in call for call in client.calls)

    def test_realtime_conversation_without_containers_sends_no_key(
        self, monkeypatch
    ):
        paused = _with_container(
            pause_turn_response(searched_urls=[SEARCHED_URL]), None
        )
        _result, client = _run_realtime(
            monkeypatch, [paused, _verdict_message(None)]
        )
        assert all("container" not in call for call in client.calls)
