"""Code-execution container continuity across ``pause_turn`` resumes.

``web_search_20260209`` / ``web_fetch_20260209`` default their
``allowed_callers`` to ``["code_execution_20260120"]`` — dynamic filtering
runs the search from inside a code-execution container that the API
provisions automatically (both web tools share one). That container is
invisible until a turn PAUSES mid-filter: the paused assistant content then
carries tool uses generated by code execution that have not completed, and a
continuation that does not name the container is rejected outright:

    HTTP 400 invalid_request_error: container_id is required when there are
    pending tool uses generated by code execution with tools.

This is not a degradation — an unnamed container makes the resume
*unissuable*, so every token the paused turn already spent is lost. It was
observed in production killing two of four research dimensions on a single
run, each after ~20 searches and a full minute of billed work.

There are exactly three ``pause_turn`` resume sites, and all three are
covered below because a site that forgets the container does not fail
gracefully:

1. the research fan-out loop (``requirements_research``),
2. the real-time verifier loop (``verifier._run_verification_call``),
3. the batch continuation builder (``verifier`` wave loop →
   ``verification_routing.build_verification_request``).

**The negative case is load-bearing too.** A conversation that never
provisioned a container must send no ``container`` key at all, so initial
requests — and every request under a tool configuration that does not use
code execution — keep a byte-identical body. `TestNoContainerKeepsBodyIdentical`
is what stops the fix from becoming a silent request-shape change.

The request contract is a top-level ``container`` parameter holding the
**bare string id** (the ``{"id": ...}`` object shape is what the *response*
carries, not what the request takes); a container is checkpointed after ~5
minutes of inactivity and restored by any request naming it inside the
30-day expiry window, which is why this is safe across the long gaps between
batch verification waves and not only inside tight real-time loops.
"""
