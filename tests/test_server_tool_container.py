def _run_realtime(monkeypatch, responses: list):
    client = _FakeClient(_sequential(responses))
    monkeypatch.setattr(V, "_get_client", lambda **_: client)
    result = V.verify_finding(
        _finding(), max_retries=0, cycle=DEFAULT_CYCLE, cache=None
    )
    return result, client


def _verdict_message(container_id: str | None = None):
    """A terminal, grounded verdict response, optionally carrying a container."""
    return _with_container(
        verification_tool_use_response(),
        container_id,
    )


class TestRealtimeVerifierContinuationCarriesContainer:
    def test_resume_after_a_pause_names_the_container(self, monkeypatch):
        paused = _with_container(
            pause_turn_response(searched_urls=[SEARCHED_URL]), CONTAINER_ID
        )
        _result, client = _run_realtime(
            monkeypatch, [paused, _verdict_message(CONTAINER_ID)]
        )

        assert len(client.calls) == 2
        assert "container" not in client.calls[0]
        assert client.calls[1]["container"] == CONTAINER_ID

    def test_container_survives_a_turn_that_reports_none(self, monkeypatch):
        first = _with_container(
            pause_turn_response(searched_urls=[SEARCHED_URL]), CONTAINER_ID
        )
        second = _with_container(pause_turn_response(), None)
        _result, client = _run_realtime(
            monkeypatch, [first, second, _verdict_message(None)]
        )

        assert len(client.calls) == 3
        assert client.calls[1]["container"] == CONTAINER_ID
        assert client.calls[2]["container"] == CONTAINER_ID


