def _classify(monkeypatch, contexts: dict, message):
    job = BatchJob(
        batch_id="container-test",
        job_type="verify",
        request_map={cid: {"model": "claude-sonnet-5"} for cid in contexts},
        created_at=0.0,
    )
    monkeypatch.setattr(
        V,
        "retrieve_verification_results_detailed",
        lambda _job: {
            cid: batch_verification_result(cid, message=message) for cid in contexts
        },
    )
    outcomes = V._classify_wave_results(
        job=job, findings=[_finding()], request_contexts=contexts
    )
    assert len(outcomes) == 1
    return outcomes[0]


class TestBatchContinuationCarriesContainer:
    def test_pause_outcome_records_the_container_id(self, monkeypatch):
        outcome = _classify(
            monkeypatch,
            {"verify__0": {"finding_idx": 0, "model": "claude-sonnet-5"}},
            _with_container(
                pause_turn_response(searched_urls=[SEARCHED_URL]), CONTAINER_ID
            ),
        )
        assert outcome.classification == "continue"
        assert outcome.container_id == CONTAINER_ID

    def test_prior_container_id_is_carried_when_a_wave_reports_none(
        self, monkeypatch
    ):
        """Wave N+2 must resume into the container wave N created."""
        outcome = _classify(
            monkeypatch,
            {
                "verify_cont_1__verify__0": {
                    "finding_idx": 0,
                    "model": "claude-sonnet-5",
                    "prior_container_id": CONTAINER_ID,
                }
            },
            _with_container(pause_turn_response(), None),
        )
        assert outcome.container_id == CONTAINER_ID

    def test_continuation_request_body_carries_the_container(self):
        request = V._build_continuation_request(
            "original prompt",
            [{"type": "text", "text": "prior turn"}],
            cycle=DEFAULT_CYCLE,
            model="claude-sonnet-5",
            severity="HIGH",
            finding=_finding(),
            container_id=CONTAINER_ID,
        )
        assert request.params["container"] == CONTAINER_ID

    def test_container_is_a_body_field_not_a_transport_header(self):
        """It must ride ``params`` so the batch API's per-item body carries it;
        ``extra_headers`` is the SDK transport seam and the batch API rejects
        unknown body keys, so getting this backwards fails in opposite ways on
        the two transports."""
        request = V._build_continuation_request(
            "original prompt",
            [{"type": "text", "text": "prior turn"}],
            cycle=DEFAULT_CYCLE,
            model="claude-sonnet-5",
            severity="HIGH",
            finding=_finding(),
            container_id=CONTAINER_ID,
        )
        assert "container" not in (request.extra_headers or {})
        assert "container" in request.params


