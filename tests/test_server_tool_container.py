class TestContainerHelpers:
    def test_reads_id_from_an_sdk_style_response(self):
        response = FakeMessage(content=[], container=FakeContainer(id=CONTAINER_ID))
        assert container_id_from_response(response) == CONTAINER_ID

    def test_reads_id_from_a_plain_dict_response(self):
        assert (
            container_id_from_response({"container": {"id": CONTAINER_ID}})
            == CONTAINER_ID
        )

    def test_accepts_an_already_bare_id(self):
        """A caller round-tripping its own request value must not lose it."""
        assert container_id_from_response({"container": CONTAINER_ID}) == CONTAINER_ID

    @pytest.mark.parametrize(
        "response",
        [
            FakeMessage(content=[]),                      # no code execution ran
            {"container": None},                          # explicit null
            {"container": {}},                            # object without an id
            {"container": {"id": ""}},                    # empty id
            {},                                           # no key at all
            SimpleNamespace(),                            # legacy / mocked object
        ],
    )
    def test_returns_none_when_no_usable_id_is_present(self, response):
        assert container_id_from_response(response) is None

    def test_never_raises_on_a_hostile_response(self):
        """Reading transport metadata must not sink the call it enables."""

        class Exploding:
            @property
            def container(self):
                raise RuntimeError("boom")

        assert container_id_from_response(Exploding()) is None

    def test_apply_writes_the_bare_string_not_the_response_wrapper(self):
        """The request parameter is the id itself; ``{"id": ...}`` is a 400."""
        params: dict = {}
        apply_container_config(params, CONTAINER_ID)
        assert params == {"container": CONTAINER_ID}

    @pytest.mark.parametrize("empty", [None, ""])
    def test_apply_is_a_no_op_without_an_id(self, empty):
        params = {"model": "claude-sonnet-5"}
        apply_container_config(params, empty)
        assert params == {"model": "claude-sonnet-5"}
        assert "container" not in params


